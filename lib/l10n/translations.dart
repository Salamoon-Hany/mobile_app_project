String translateText(String text, String language) {
  final ar = language == 'ar';
  if (!ar) {
    final step = RegExp(r'^خطوة (\d+) من (\d+)$').firstMatch(text);
    if (step != null) return 'Step ${step[1]} of ${step[2]}';
    return englishIntroStrings[text] ?? text;
  }
  final exact = arabicStrings[text];
  if (exact != null) return exact;
  if (text.startsWith('EGP ')) return '${text.substring(4)} ج.م';
  final patterns = <(RegExp, String Function(Match))>[
    (
      RegExp(r'^Balance: (.+)$'),
      (m) => 'الرصيد: ${translateText(m[1]!, language)}',
    ),
    (
      RegExp(r'^(.+) added to your balance\.$'),
      (m) => 'تمت إضافة ${translateText(m[1]!, language)} لرصيدك.',
    ),
    (RegExp(r'^Resend in (\d+)s$'), (m) => 'إعادة الإرسال بعد ${m[1]} ثانية'),
    (
      RegExp(r'^Retry SMS in (\d+)s$'),
      (m) => 'إعادة إرسال الكود بعد ${m[1]} ثانية',
    ),
    (RegExp(r'^Error: (.+)$'), (m) => 'خطأ: ${translateText(m[1]!, language)}'),
    (RegExp(r'^Selected: (.+)$'), (m) => 'المكان المختار: ${m[1]}'),
    (RegExp(r'^Reference: (.+)$'), (m) => 'المرجع: ${m[1]}'),
    (
      RegExp(r'^(\d+)(s|m|h|d) ago$'),
      (m) =>
          'منذ ${m[1]} ${{'s': 'ثانية', 'm': 'دقيقة', 'h': 'ساعة', 'd': 'يوم'}[m[2]]}',
    ),
    (RegExp(r'^Invite sent to (.+)!$'), (m) => 'تم إرسال الدعوة إلى ${m[1]}!'),
    (
      RegExp(r'^Send job invite to (.+)\?$'),
      (m) => 'إرسال دعوة الخدمة إلى ${m[1]}؟',
    ),
    (
      RegExp(r'^You sent an invite to (.+)\. Waiting for response\.\.\.$'),
      (m) => 'أرسلت دعوة إلى ${m[1]}. في انتظار الرد…',
    ),
    (
      RegExp(r'^Your (.+) order has been (accepted!|rejected\.)$'),
      (m) =>
          'تم ${m[2] == 'accepted!' ? 'قبول' : 'رفض'} طلب ${translateText(m[1]!, language)}.',
    ),
    (
      RegExp(r'^SMS requested for (.+)\. Enter the code when it arrives\.$'),
      (m) => 'تم طلب كود لرقم ${m[1]}. اكتبه لما يوصلك.',
    ),
    (
      RegExp(
        r'^Open the verification link sent to (.+)\. Then return here to continue\.$',
      ),
      (m) => 'افتح رابط التحقق المرسل إلى ${m[1]}، وبعدها ارجع هنا عشان تكمّل.',
    ),
    (RegExp(r'^(\d+) jobs • ⭐(.+)$'), (m) => '${m[1]} خدمة • ⭐${m[2]}'),
    (
      RegExp(
        r'^⚠️ Low Balance! Your balance is (.+), but this order costs EGP (.+)$',
      ),
      (m) =>
          '⚠️ الرصيد غير كافٍ! رصيدك ${translateText(m[1]!, language)}، وتكلفة الطلب ${m[2]} ج.م',
    ),
    (
      RegExp(
        r'^Firebase could not finish \((.+)\)\. Please share this code so the setup can be checked\.$',
      ),
      (m) => 'تعذّر إكمال التحقق (${m[1]}). أرسل الكود ده لمراجعة الإعدادات.',
    ),
    (
      RegExp(
        r'^Verification could not finish \((.+)\)\. Try again and share this error label if it continues\.$',
      ),
      (m) =>
          'تعذّر إكمال التحقق (${m[1]}). حاول تاني وأرسل الكود لو استمر الخطأ.',
    ),
  ];
  for (final (pattern, render) in patterns) {
    final match = pattern.firstMatch(text);
    if (match != null) return render(match);
  }
  if (text.contains(', ')) {
    final parts = text.split(', ');
    if (parts.every(arabicStrings.containsKey)) {
      return parts.map((p) => arabicStrings[p]!).join('، ');
    }
  }
  return text;
}
